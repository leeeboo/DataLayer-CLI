export function languageFrom(value) {
  const locale = String(value || 'en').replaceAll('_', '-').toLowerCase();
  const exact = Object.keys(languages).find(code => code.toLowerCase() === locale);
  if (exact) return exact;
  if (/^zh-(tw|hk|hant)(-|$)/.test(locale)) return 'zh-TW';
  if (/^zh(-|$)/.test(locale)) return 'zh-CN';
  if (/^pt(-|$)/.test(locale)) return 'pt-BR';
  const base = locale.split('-')[0];
  return Object.hasOwn(languages, base) ? base : 'en';
}
export function translate(language, key, details = {}) {
  const template = translations[language]?.[key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(details[name] ?? `{${name}}`));
}
export function errorMessage(error, language) {
  const key = Object.hasOwn(translations.en, error?.code) ? error.code : error instanceof SyntaxError ? 'errorJSON' : 'errorUnknown';
  return translate(language, key, error?.details);
}
